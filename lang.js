(function () {
  var saved = 'en';
  try { saved = localStorage.getItem('site_lang') || 'en'; } catch (e) {}

  function t(key, code) {
    return (I18N[code] && I18N[code][key]) || null;
  }

  function applyLang(code) {
    try { localStorage.setItem('site_lang', code); } catch (e) {}
    document.documentElement.lang = code;
    document.documentElement.dir = (code === 'ur') ? 'rtl' : 'ltr';
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var k = el.getAttribute('data-i18n');
      if (el.dataset.i18nEn === undefined) el.dataset.i18nEn = el.textContent;
      if (code === 'en') { el.textContent = el.dataset.i18nEn; }
      else { var v = t(k, code); if (v) el.textContent = v; }
    });
    document.querySelectorAll('[data-i18n-ph]').forEach(function (el) {
      var k = el.getAttribute('data-i18n-ph');
      if (el.dataset.i18nEnPh === undefined) el.dataset.i18nEnPh = el.getAttribute('placeholder') || '';
      if (code === 'en') { el.setAttribute('placeholder', el.dataset.i18nEnPh); }
      else { var v = t(k, code); if (v) el.setAttribute('placeholder', v); }
    });
    var sel = document.getElementById('langSel');
    if (sel) sel.value = code;
  }

  function inject() {
    var nav = document.querySelector('.top nav');
    if (!nav || document.getElementById('langSel')) return;
    var s = document.createElement('select');
    s.id = 'langSel';
    s.className = 'langsel';
    s.innerHTML = '<option value="en">🌐 English</option><option value="ur">🌐 اردو</option>';
    s.setAttribute('title', 'Language / زبان');
    s.onchange = function () { applyLang(s.value); };
    nav.appendChild(s);
  }

  inject();
  applyLang(saved);
})();
